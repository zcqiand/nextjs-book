# 启动开发服务器
npm run dev

# 路径一（正常提交）：
#   1. 浏览器打开 http://localhost:3000/tasks/101
#   2. 在「写下你的评论」输入「乐观更新真省心」，点击「发送」
#      → 评论立刻上屏（此时请求还在路上），片刻后仍留在列表里，刷新页面也不丢

# 路径二（强制失败回滚）：
#   3. 输入「这条一定会失败 [fail]」，点击「发送」
#      → 评论先上屏，随即消失，评论区出现红色横幅「评论发送失败，已撤销本次显示，请重试」

# 可选：用 curl 确认详情页可正常访问
curl -s -o /dev/null -w "%{http_code}\n" http://localhost:3000/tasks/101
# 预期输出：200