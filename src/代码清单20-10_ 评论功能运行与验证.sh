# 启动开发服务器
npm run dev

# curl 只验证详情页渲染，提交表单走下面的浏览器步骤
curl -I http://localhost:3000/tasks/101
# 预期输出首行：HTTP/1.1 200 OK

# 浏览器提交步骤：
#   1. 打开 http://localhost:3000/tasks/101
#   2. 填写署名（如：林一舟）与评论内容，点击「提交评论」
#   3. 页面刷新后评论列表出现这条评论，计数从 0 变为 1

# 说明：Server Action 的提交请求由 Next.js 框架在服务端接管处理，
# 用 curl 手工构造请求无法通过框架校验，提交类验证请走浏览器步骤